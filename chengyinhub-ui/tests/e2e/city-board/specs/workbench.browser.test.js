test('definite 400 rejection clears pending state and permits an explicit corrected save', async ({ page, city }) => {
  await openWorkbench(page); await fillDraft(page)
  const bad = city.holdNext('save')
  await button(page, '保存新版本 / Save version').click(); await bad.seen
  bad.release({ json: { code: 400, errorCode: 'INTEGER_REQUIRED', msg: 'INTEGER_REQUIRED' } })
  await expect(page.locator('.city-draft [role="alert"]')).toHaveText('INTEGER_REQUIRED')
  await expect(nameField(page)).toBeEnabled()
  await expect(button(page, '重试原保存 / Retry exact save')).toHaveCount(0)
  await nameField(page).fill('纠正后的合成草稿')
  await saveDraft(page)
  expect(city.callsOf('save')).toHaveLength(2)
  expect(city.callsOf('save')[1].body.requestId).not.toBe(city.callsOf('save')[0].body.requestId)
  expect(city.callsOf('save')[1].body.payload.name).toBe('纠正后的合成草稿')
})

test('409 conflict blocks edits until explicit reopen binds the newer stored revision', async ({ page, city }) => {
  await openWorkbench(page); await fillDraft(page); await saveDraft(page)
  await nameField(page).fill('本地冲突修改')
  const conflict = city.holdNext('save')
  await button(page, '保存新版本 / Save version').click(); await conflict.seen
  const latest = snapshot({ draftId: 'synthetic-draft', expectedVersion: 4, payload: { ...payload(), name: '远端合成版本' } })
  city.records.set('synthetic-draft', latest)
  conflict.release({ json: { code: 409, errorCode: 'CITY_DRAFT_CONFLICT', msg: 'CITY_DRAFT_CONFLICT' } })
  await expect(page.getByRole('status')).toHaveText(/Version conflict/)
  await expect(nameField(page)).toBeDisabled()
  await expect(button(page, '重试原保存 / Retry exact save')).toHaveCount(0)
  await dialogAction(page, 'accept', () => button(page, '重新读取 / Reopen').click())
  await expect(nameField(page)).toHaveValue('远端合成版本')
  await expect(nameField(page)).toBeEnabled()
  await button(page, '玩家只读预览 / Player preview').click()
  await expect(previewRegion(page)).toBeVisible()
  expect(city.callsOf('preview')[0].body).toEqual({ draftId: 'synthetic-draft', expectedVersion: 5, expectedHash: latest.payloadHash })
})

test('unknown server result locks the original request until explicit reopen resolves it', async ({ page, city }) => {
  await openWorkbench(page); await fillDraft(page)
  const pending = city.holdNext('save')
  await button(page, '保存新版本 / Save version').click(); await pending.seen
  pending.release({ json: { code: 500, msg: 'SYNTHETIC_UNKNOWN_RESULT' } })
  await expect(button(page, '重试原保存 / Retry exact save')).toBeEnabled()
  await expect(nameField(page)).toBeDisabled()
  await dialogAction(page, 'dismiss', () => button(page, '重新读取 / Reopen').click())
  expect(city.callsOf('reopen')).toHaveLength(0)
  await expect(button(page, '重试原保存 / Retry exact save')).toBeVisible()
  await dialogAction(page, 'accept', () => button(page, '重新读取 / Reopen').click())
  await expect(page.getByRole('status')).toHaveText(/Saved version reopened/)
  await expect(button(page, '重试原保存 / Retry exact save')).toHaveCount(0)
  expect(city.callsOf('save')).toHaveLength(1)
})

test('native Back and Forward discard a late save without restoring abandoned data', async ({ page, city }) => {
  await prepareHistory(page); await fillDraft(page)
  const pending = city.holdNext('save')
  await button(page, '保存新版本 / Save version').click(); await pending.seen
  await page.goBack(); await expect(page).toHaveURL(ORIGIN + AWAY)
  await settleResponse(page, pending, { json: { code: 200, data: snapshot((await pending.seen).body) } })
  await page.goForward(); await expect(page).toHaveURL(ORIGIN + WORKBENCH)
  await expect(nameField(page)).toBeEnabled(); await assertCleared(page)
  expect(city.callsOf('save')).toHaveLength(1)
  expect(city.callsOf('reopen')).toHaveLength(0)
})

test('late preview 401 after native Back cannot prompt login or log out the current page', async ({ page, city }) => {
  await prepareHistory(page); await fillDraft(page); await saveDraft(page)
  const pending = city.holdNext('preview')
  await button(page, '玩家只读预览 / Player preview').click(); await pending.seen
  await page.goBack(); await expect(page).toHaveURL(ORIGIN + AWAY)
  await settleResponse(page, pending, { json: { code: 401, msg: 'SYNTHETIC_RETIRED_SESSION' } })
  await expect(page.locator('.el-message-box')).toBeHidden()
  expect(city.callsOf('logout')).toHaveLength(0)
  await page.goForward(); await expect(page).toHaveURL(ORIGIN + WORKBENCH)
  await assertCleared(page)
})

test('[browser-integration] synchronous session ABA retires a late save in the actual Vuex request chain', { tag: ['@integration'] }, async ({ page, city, context }) => {
  await openWorkbench(page); await fillDraft(page)
  const pending = city.holdNext('save')
  await button(page, '保存新版本 / Save version').click(); await pending.seen
  await sessionABA(page)
  await settleResponse(page, pending, { json: { code: 200, data: snapshot((await pending.seen).body) } })
  await expect(nameField(page)).toBeEnabled(); await assertCleared(page)
  expect((await context.cookies()).find(cookie => cookie.name === 'Admin-Token').value).toBe(TOKEN_A)
  expect(city.callsOf('save')).toHaveLength(1); expect(city.callsOf('logout')).toHaveLength(0)
})

test('[browser-integration] session ABA after a current 401 prompt prevents a confirmed stale logout', { tag: ['@integration'] }, async ({ page, city, context }) => {
  await openWorkbench(page); await fillDraft(page)
  const pending = city.holdNext('save')
  await button(page, '保存新版本 / Save version').click(); await pending.seen
  pending.release({ json: { code: 401, msg: 'SYNTHETIC_CURRENT_SESSION_EXPIRED' } })
  const prompt = page.locator('.el-message-box')
  await expect(prompt).toBeVisible()
  await sessionABA(page)
  await prompt.getByRole('button', { name: /重新登录/ }).click()
  await expect(prompt).toBeHidden()
  await expect(page).toHaveURL(ORIGIN + WORKBENCH)
  await expect(nameField(page)).toBeEnabled(); await assertCleared(page)
  expect((await context.cookies()).find(cookie => cookie.name === 'Admin-Token').value).toBe(TOKEN_A)
  expect(city.callsOf('logout')).toHaveLength(0)
})
