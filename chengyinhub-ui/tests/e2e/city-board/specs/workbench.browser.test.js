const { test, expect, ORIGIN, WORKBENCH, AWAY, TOKEN_A, LABELS, REFLABELS, payload,
  snapshot, openWorkbench, fillDraft, saveDraft, prepareHistory, settleResponse, sessionABA } = require('./fixture')
const button = (page, name) => page.getByRole('button', { name, exact: true })
const nameField = page => page.getByLabel('名称 / Name', { exact: true })
const previewRegion = page => page.getByRole('region', { name: 'Player read-only preview', exact: true })
async function dialogAction(page, action, click) {
  const dialog = page.waitForEvent('dialog')
  const clicked = click()
  const current = await dialog
  expect(current.type()).toBe('confirm')
  await current[action]()
  await clicked
}
async function assertCleared(page) {
  await expect(nameField(page)).toHaveValue('')
  await expect(page.getByLabel('草稿 ID / Draft ID', { exact: true })).toHaveValue('')
  await expect(page.getByText('已保存版本 / Saved version:', { exact: false })).toHaveCount(0)
  await expect(previewRegion(page)).toHaveCount(0)
  await expect(button(page, '重试原保存 / Retry exact save')).toHaveCount(0)
}

