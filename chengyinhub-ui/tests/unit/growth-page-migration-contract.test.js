const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const uiRoot = path.resolve(__dirname, '../..')
const growthPage = fs.readFileSync(path.join(uiRoot, 'src/views/business/growth/index.vue'), 'utf8')
const memberPage = fs.readFileSync(path.join(uiRoot, 'src/views/business/member/index.vue'), 'utf8')
const router = fs.readFileSync(path.join(uiRoot, 'src/router/index.js'), 'utf8')
const growthApi = fs.readFileSync(path.join(uiRoot, 'src/api/business/growth.js'), 'utf8')
const detailPath = path.join(uiRoot, 'src/views/business/member/growth-detail.vue')

test('成长菜单只承载任务配置，不再把会员成长账户作为独立查询入口', () => {
  assert.match(growthPage, /成长任务配置/)
  assert.match(growthPage, /CyPageHeader/)
  assert.match(growthPage, /CyFilterBar/)
  assert.match(growthPage, /listGrowthMissions/)
  assert.match(growthPage, /saveGrowthMission/)
  assert.match(growthPage, /missionDesc/)
  assert.doesNotMatch(growthPage, /dailyLimit|每日上限/)
  assert.match(growthPage, /任务已保存，但列表刷新失败/)
  assert.doesNotMatch(growthPage, /listGrowthMembers|memberList|queryParams\.memberId|label="会员ID"|暂无成长账户/)
  assert.doesNotMatch(growthApi, /listGrowthMembers/)
})

test('会员成长作为用户 360 的权限保护详情子页，而不是第二张会员列表', () => {
  assert.ok(fs.existsSync(detailPath), '应建立会员成长详情页')
  const detailPage = fs.readFileSync(detailPath, 'utf8')

  assert.match(memberPage, /memberGrowthDetail/)
  assert.match(memberPage, /viewGrowthDetail/)
  assert.match(router, /path:\s*'\/customer\/member'/)
  assert.match(router, /path:\s*':memberId\/growth'/)
  assert.match(router, /name:\s*'memberGrowthDetail'/)
  assert.match(router, /permissions:\s*\['business:member:list'\]/)
  assert.match(detailPage, /getMemberGrowthCenter/)
  assert.match(detailPage, /this\.\$route\.params\.memberId/)
  assert.doesNotMatch(detailPage, /dailyLimit|每日上限/)
  assert.match(growthApi, /\/business\/growth\/member\/\' \+ memberId/)
})
