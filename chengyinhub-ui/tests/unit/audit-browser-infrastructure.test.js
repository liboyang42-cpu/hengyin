/** Infrastructure unit checks. These are not browser execution evidence. */
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { resolveRequest, bundleScripts, HOST, PORT } = require('../e2e/server/audit-static-server')
const ROOT = path.resolve(__dirname, '../../..')
const UI = path.resolve(__dirname, '../..')
const read = relative => fs.readFileSync(path.join(ROOT, relative), 'utf8')

test('audit static host binds loopback and only exposes bundle assets and explicit SPA routes', () => {
  assert.equal(HOST, '127.0.0.1')
  assert.equal(PORT, 4173)
  assert.deepEqual(resolveRequest('/audit-center/audit?bizId=9101'), { status: 200, file: 'index.html' })
  assert.deepEqual(resolveRequest('/static/js/app.123.js'), { status: 200, file: 'static/js/app.123.js' })
  assert.equal(resolveRequest('/prod-api/business/audit/list').status, 404)
  assert.equal(resolveRequest('/dev-api/business/audit/list').status, 404)
  assert.equal(resolveRequest('/business/audit/list').status, 404)
  assert.equal(resolveRequest('/anything-else').status, 404)
  assert.equal(resolveRequest('/prod-api/business/audit/review', 'POST').status, 405)
  assert.equal(resolveRequest('/static/%2e%2e%2f.env').status, 403)
  assert.equal(resolveRequest('/static/%5c..%5c.env').status, 403)
  assert.equal(resolveRequest('/%invalid').status, 400)
})

test('browser gate consumes the existing production build after all ordinary gates', () => {
  const workflow = read('.github/workflows/ci.yml')
  const job = workflow.split('  admin_ui:\n')[1].split('\n  admin_ui_contract:')[0]
  assert.match(job, /needs\.changes\.outputs\.ui == 'true'/)
  const build = job.indexOf('run: bash ci/ui-build.sh "${{ github.sha }}"')
  const install = job.indexOf('playwright install --with-deps chromium')
  const browser = job.indexOf('run: npm run test:e2e:audit')
  assert.ok(build >= 0 && install > build && browser > install)
  assert.doesNotMatch(job, /continue-on-error|pass-with-no-tests|passWithNoTests|secrets\.|permissions:\s*write-all|E2E_BASE_URL/)
  assert.match(job, /actions\/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02/)
  assert.match(job, /if-no-files-found: error/)
  const buildScript = read('ci/ui-build.sh')
  assert.ok(buildScript.indexOf('npm run test:unit') < buildScript.indexOf('npm run build:prod'))
  assert.ok(buildScript.indexOf('npm run test:e2e:contract') < buildScript.indexOf('npm run build:prod'))
  const pkg = JSON.parse(fs.readFileSync(path.join(UI, 'package.json'), 'utf8'))
  const lock = JSON.parse(fs.readFileSync(path.join(UI, 'package-lock.json'), 'utf8'))
  assert.equal(pkg.scripts['test:e2e:audit'], 'node tests/e2e/run-audit-browser.js')
  assert.equal(lock.packages['node_modules/@playwright/test'].version, '1.62.0')
})

test('audit runner is separate from old skeletons and cannot connect to a live server', () => {
  const config = fs.readFileSync(path.join(UI, 'tests/e2e/playwright.audit.config.js'), 'utf8')
  assert.match(config, /testDir: '\.\/audit'/)
  assert.match(config, /baseURL: 'http:\/\/127\.0\.0\.1:4173'/)
  assert.match(config, /reuseExistingServer: false/)
  assert.match(config, /serviceWorkers: 'block'/)
  assert.match(config, /forbidOnly: true/)
  assert.match(config, /retries: 0/)
  assert.doesNotMatch(config, /process\.env\.E2E_BASE_URL|http-server|--proxy|executablePath|launchOptions/)
  const fixture = fs.readFileSync(path.join(UI, 'tests/e2e/audit/fixture.js'), 'utf8')
  assert.match(fixture, /context\.route\('\*\*\/\*'/)
  assert.match(fixture, /classifyRequest\(/)
  assert.match(fixture, /route\.abort\('blockedbyclient'\)/)
  assert.match(fixture, /context\.routeWebSocket/)
  assert.match(fixture, /route\.fetch\(\{ maxRedirects: 0[, }]/)
  assert.doesNotMatch(fixture, /route\.continue\(|connectToServer\(|storageState:|process\.env/)
  assert.match(config, /globalTimeout: 8 \* 60 \* 1000/)
})


test('production index validation accepts Vue CLI minified unquoted script attributes', () => {
  assert.deepEqual(bundleScripts('<script src=/static/js/app.abcd.js></script>'), ['/static/js/app.abcd.js'])
  assert.deepEqual(bundleScripts('<script defer src="/static/js/app.abcd.js"></script>'), ['/static/js/app.abcd.js'])
  assert.deepEqual(bundleScripts('<script src="https://elsewhere.invalid/app.js"></script>'), [])
  assert.deepEqual(bundleScripts('<div id="app">test-only HTML is not a production bundle</div>'), [])
})
