/** Source/provenance controls are not browser execution evidence. */
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const vm = require('node:vm')
const { OUTPUT, RECEIPT, COMMAND, ENV, inventory, inputs, verifyReceipt } = require('../e2e/city-board/bundle-provenance')
const { buildEnvironment } = require('../e2e/city-board/build')
const UI = path.resolve(__dirname, '../..')
const read = relative => fs.readFileSync(path.join(UI, relative), 'utf8')
test('isolated build scrubs inherited feature flags and preserves the ordinary production output', () => {
  const env = buildEnvironment({ VUE_APP_CITY_BOARD_DRAFTS: 'bad', VUE_APP_BASE_API: 'https://external.invalid', VUE_APP_OTHER: 'bad', NODE_OPTIONS: '--require bad', NODE_PATH: '/bad', PATH: '/safe' })
  assert.deepEqual(env, { PATH: '/safe', ...ENV })
  const build = read('tests/e2e/city-board/build.js')
  assert.match(build, /GITHUB_ACTIONS !== 'true'.*CI !== 'true'/)
  assert.match(build, /verifyProduction\(UI_ROOT, receipt.commit\)/)
  assert.match(build, /'--dest', OUTPUT/)
  assert.doesNotMatch(build, /writeFileSync.*src|writeFileSync.*\.env|npm install/)
  assert.equal(OUTPUT, 'tests/e2e/evidence/city-board-dist')
  assert.match(read('src/api/business/city-board-drafts.js'), /process\.env\.VUE_APP_CITY_BOARD_DRAFTS === 'true'/)
  assert.match(read('src/router/index.js'), /process\.env\.VUE_APP_CITY_BOARD_DRAFTS === 'true' \? \[/)
})
test('W20 workflow remains additive after the ordinary build and expanded audit browser gate', () => {
  const workflow = fs.readFileSync(path.join(UI, '../.github/workflows/ci.yml'), 'utf8')
  const job = workflow.split('  admin_ui:\n')[1].split('\n  admin_ui_contract:')[0]
  const positions = ['bash ci/ui-build.sh', 'playwright install --with-deps chromium', 'npm run test:e2e:audit', 'node tests/e2e/city-board/build.js', 'node tests/e2e/city-board/run.js'].map(value => job.indexOf(value))
  assert.ok(positions.every((value, i) => value >= 0 && (!i || value > positions[i - 1])))
  assert.match(job, /needs\.changes\.outputs\.ui == 'true'/)
  assert.doesNotMatch(job, /continue-on-error|pass-with-no-tests|secrets\.|permissions:\s*write-all|E2E_BASE_URL/)
  assert.match(job, /city-board-browser-\$\{\{ github.sha \}\}/)
  assert.match(job, /if-no-files-found: error/)
  const runner = read('tests/e2e/city-board/run.js')
  assert.match(runner, /writeFileSync\(path.join\(EVIDENCE, 'build-receipt.json'\), buildReceiptBytes, \{ flag: 'wx' \}\)/)
  assert.match(runner, /commit: receipt.commit, buildReceiptSha256, \.\.\.summary/)
  assert.match(runner, /readRegular\(dist, RECEIPT\).equals\(buildReceiptBytes\)/)
  const validator = read('tests/e2e/audit-report-validator.js')
  const audit = require('../e2e/audit-report-validator')
  assert.deepEqual(audit.FILE_COUNTS, { 'audit-console.browser.test.js': 25, 'candidate-preview.browser.test.js': 18, 'npc-generic-boundary.browser.test.js': 7 })
  assert.equal(audit.FILE_COUNTS['audit-console.browser.test.js'] + audit.FILE_COUNTS['candidate-preview.browser.test.js'], 43)
  assert.equal(audit.EXPECTED_COUNT, 50)
  assert.equal(Object.values(audit.FILE_COUNTS).reduce((sum, count) => sum + count, 0), audit.EXPECTED_COUNT)
  assert.match(validator, /integration === 5/)
})
test('12 concrete cases are registered without focus skips retries or direct UI-method calls', () => {
  const source = read('tests/e2e/city-board/specs/workbench.browser.test.js')
  const registered = []
  vm.runInNewContext(source, { require: () => ({ test: (...args) => registered.push(args) }), module: { exports: {} } })
  assert.equal(registered.length, 12)
  assert.equal(new Set(registered.map(args => args[0])).size, 12)
  assert.equal(registered.filter(args => args[0].startsWith('[browser-integration] ') && args[1].tag[0] === '@integration').length, 2)
  assert.doesNotMatch(source, /test\.(?:only|skip|fixme|fail)|__vue__|\$router|\$forceUpdate|evaluate\(/)
  assert.doesNotMatch(read('tests/e2e/city-board/specs/fixture.js'), /__vue__|\$router|route\.continue\(|process\.env|storageState/)
  assert.match(read('tests/e2e/city-board/specs/session-integration.js'), /Explicitly tagged integration/)
  const config = read('tests/e2e/city-board/playwright.config.js')
  assert.match(config, /testDir: '\.\/specs'/)
  for (const required of ['forbidOnly: true', 'retries: 0', "serviceWorkers: 'block'", 'reuseExistingServer: false']) assert.ok(config.includes(required))
  assert.doesNotMatch(config, /executablePath|launchOptions|process\.env/)
})
test('test receipt rejects changed source harness flags output commit and symlinks', () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'city-board-provenance-unit-'))
  const commit = 'a'.repeat(40), dist = path.join(temp, OUTPUT)
  try {
    for (const dir of ['src', 'public', 'build', 'tests/e2e/city-board', `${OUTPUT}/static/js`]) fs.mkdirSync(path.join(temp, dir), { recursive: true })
    for (const file of ['src/main.js', 'public/index.html', 'package.json', 'package-lock.json', 'vue.config.js', 'tests/e2e/city-board/build.js']) fs.writeFileSync(path.join(temp, file), `unit-control ${file}`)
    fs.writeFileSync(path.join(dist, 'index.html'), '<script src=/static/js/app.abcd.js></script>')
    fs.writeFileSync(path.join(dist, 'static/js/app.abcd.js'), 'unit control only, not application evidence')
    const receipt = { schema: 1, purpose: 'SYNTHETIC_API_BROWSER_ONLY', command: COMMAND, environment: ENV, commit, builtAt: '2026-01-01T00:00:00Z', inputs: inputs(temp), outputs: inventory(dist, fs.readdirSync(dist).sort()) }
    const stamp = value => fs.writeFileSync(path.join(dist, RECEIPT), JSON.stringify(value))
    stamp(receipt); assert.equal(verifyReceipt(temp, commit).receipt.commit, commit)
    assert.throws(() => verifyReceipt(temp, 'b'.repeat(40)), /commit/)
    stamp({ ...receipt, environment: { ...ENV, VUE_APP_CITY_BOARD_DRAFTS: 'false' } }); assert.throws(() => verifyReceipt(temp, commit), /receipt/); stamp(receipt)
    for (const file of ['src/main.js', 'tests/e2e/city-board/build.js']) {
      const p = path.join(temp, file), old = fs.readFileSync(p)
      fs.appendFileSync(p, 'changed'); assert.throws(() => verifyReceipt(temp, commit), /inputs/); fs.writeFileSync(p, old)
    }
    const p = path.join(dist, 'static/js/app.abcd.js'), old = fs.readFileSync(p)
    fs.appendFileSync(p, 'changed'); assert.throws(() => verifyReceipt(temp, commit), /bundle/); fs.writeFileSync(p, old)
    fs.writeFileSync(path.join(dist, 'unexpected.js'), 'unexpected'); assert.throws(() => verifyReceipt(temp, commit), /bundle/); fs.unlinkSync(path.join(dist, 'unexpected.js'))
    fs.unlinkSync(p); assert.throws(() => verifyReceipt(temp, commit), /bundle/)
    fs.symlinkSync(path.join(temp, 'src/main.js'), p); assert.throws(() => verifyReceipt(temp, commit), /symlink/)
  } finally { fs.rmSync(temp, { recursive: true, force: true }) }
})
