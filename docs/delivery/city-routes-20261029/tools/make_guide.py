def station_block(n, s):
    g = s["game"]
    lines = [f"#### 第 {n} 站：{s['name']}", "",
             f"- 站名（名称）：`{s['name']}`",
             f"- 选点搜索词：`{s['poi']}`；核对用 GCJ-02 估值：`{s['gcj02'][0]}, {s['gcj02'][1]}`（{s['precision']}）",
             f"- 地址备注：{s['address']}；{s['access']}",
             f"- 照片：{'；'.join(s['images'])}", "",
             "地点**之前**的文字块（原文照贴）：", "", "```text", s["arrive"], "```", "",
             f"玩法编辑页：名字 `{g['template_name']}`｜玩法看点 `{g['highlight']}`｜所需材料 `{g['materials']}`｜参与方式「定位到达」｜{g['picker_path']}", "",
             "| 玩法设置字段 | 填写 |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in g["ui_fields"]]
    if g["config"].get("qa", {}).get("options"):
        lines += ["", "每个选项的「选中后的反馈」：", ""]
        lines += [f"- {o['label']}{'（正确）' if o.get('correct') else ''}：{o['fb']}" for o in g["config"]["qa"]["options"]]
    lines += ["", "结果反馈 → 完成／成功反馈 → 回复一句：", "", "```text", g["pass"], "```", ""]
    if g.get("fail"):
        lines += ["结果反馈 → 失败反馈 → 回复一句：", "", "```text", g["fail"], "```", ""]
    return lines


def main():
    out = [HEAD]
    for rid in IDS:
        r = json.load(open(os.path.join(ROOT, "routes", rid, "route.json"), encoding="utf-8"))
        t = r["theme"]
        st = {s["id"]: s for s in r["stations"]}
        out += [f"\n---\n\n# 线路：《{t['name']}》\n",
                "## 主题页取值", "",
                f"- 主题名称：`{t['name']}`",
                f"- 主题描述：`{t['subtitle']}`",
                f"- 主题类别：{t['category_hint']}",
                f"- 竖版封面：`images/covers/{rid}/cover-3x4.jpg`；横版封面：`images/covers/{rid}/cover-16x9.jpg`",
                f"- 可玩时段：{t['play_time']}",
                f"- 通关勋章（仅俱乐部负责人可改）：`{t['medal']}`", "",
                "剧情详情（原文照贴）：", "", "```text", t["description"], "```", ""]
        n = 0
        for ci, ch in enumerate(r["chapters"], 1):
            out += [f"### 第 {ci} 章：章节名称 `{ch['name']}`", "",
                    f"章节剧情（选填）：`{ch['summary']}`", "",
                    "故事流块顺序：" + " → ".join(["文字块 + 地点「" + st[sid]["name"] + "」" for sid in ch["stations"]]) + (" → 章末文字块" if ch.get("outro") else ""), ""]
            for sid in ch["stations"]:
                n += 1
                out += station_block(n, st[sid])
            if ch.get("outro"):
                out += ["本章最后一个地点**之后**的文字块（原文照贴）：", "", "```text", ch["outro"], "```", ""]
        first = r["stations"][0]
        tip = "沿途只在街面观看，不进入学校、居民楼和办公区；注意交通安全。" if rid == "commercial-press" else "外滩各站只看外立面；邮政博物馆周三、四、六、日开放；注意交通安全。"
        out += [TICKET.format(name=t["name"], first=first["poi"], tip=tip)]
    out += [TAIL]
    open(os.path.join(ROOT, "publish-guide.md"), "w", encoding="utf-8").write("\n".join(out))
    print("wrote publish-guide.md")


if __name__ == "__main__":
    main()
