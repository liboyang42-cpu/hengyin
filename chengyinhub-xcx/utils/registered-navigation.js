function navigateRegistered(options, method) {
  const url = options && options.url;
  const target = typeof url === 'string' && url.startsWith('/') ? url.split(/[?#]/)[0].slice(1) : '';
  const action = method || 'navigateTo';
  if (!REGISTERED_PATHS.includes(target) || !['navigateTo', 'redirectTo', 'reLaunch'].includes(action)) {
    toast('这个入口暂时打不开，请返回重试');
    const error = { errMsg: action + ':fail invalid registered route' };
    try { if (options && typeof options.fail === 'function') options.fail(error); }
    finally { if (options && typeof options.complete === 'function') options.complete(error); }
    return false;
  }
  return wx[action](Object.assign({}, options, { url }));
}

