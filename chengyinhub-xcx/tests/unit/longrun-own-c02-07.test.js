let pageConfig = null;
global.Page = (cfg) => { pageConfig = cfg; };

beforeEach(() => {
  memberId = 42;
  throwOnRequest = false;
  sent = [];
  storage = {};
  navigations = [];
  toasts = [];
  modals = [];
  pageConfig = null;
  delete require.cache[require.resolve(PAGE)];
  require(PAGE);
});

function makePage() {
  const inst = Object.assign({}, pageConfig);
  inst.data = JSON.parse(JSON.stringify(pageConfig.data));
  inst.setData = function (patch, cb) {
    Object.keys(patch).forEach((k) => {
      const parts = k.replace(/\[(\d+)\]/g, '.$1').split('.');
      let o = inst.data;
      for (let i = 0; i < parts.length - 1; i++) o = o[parts[i]];
      o[parts[parts.length - 1]] = patch[k];
    });
    if (cb) cb();
  };
  return inst;
}

test('synchronous publish failure cannot re-enable loading after UNKNOWN result is displayed', () => {
  const page = makePage();
  page.data.draftUuid = 'sync-throw';
  page.data.draftMemberId = 42;
  throwOnRequest = true;
  assert.doesNotThrow(() => page.sendData({ name:'topic' }));
  assert.equal(page.data.submitting, false);
  assert.equal(page.getPublishWorkflow().getState(), 'unknown');
  assert.equal(page.data.resultSheet.show, true);
  assert.equal(page._publishAttempt.status, 'UNKNOWN');
  page.sendData({ name:'topic' });
  assert.equal(sent.length, 1);
});
