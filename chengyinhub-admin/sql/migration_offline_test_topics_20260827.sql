-- 下架三条测试/垃圾主题 —— 它们即将出现在玩家首屏
--
-- 背景:公开主题查询原先被 `end_date > now()` 静默滤空(全库未过期主题 0 条),
-- 两块主题区长期全空。修掉那道闸后,过闸的非模板主题共 7 条,而公开列表
-- `order by id desc` 会把下面这三条排在最前 —— 推荐主题只取 5 条 ⇒ 首屏前三张
-- 全是测试数据。比空着更糟,所以随闸一起处理。
--
--   21 副本人生            member 100092(城市运动装备馆)
--   22 好多好多不是吧       member 100092(城市运动装备馆)
--   23 测试主题-春日漫步    member 100091(城瘾用户)
--
-- 处置:user_status = 0(下架),不删数据、不动 status、发布者仍可在「我发布的」里看到。
-- 公开 Mapper 的硬闸是 `user_status = 1`,置 0 即从所有玩家侧入口消失。
-- 随时可改回 1 还原。
--
-- ⚠️ 21/22 属于真实商家账号,本次下架是用户明确指令(2026-08-27),不是自动清理。
--
-- 幂等:WHERE 带 user_status = 1,已下架则 0 行。
-- 纯 DML,不创建/修改表结构。
-- ============================================================================

UPDATE cms_topic
   SET user_status = 0,
       update_by = 'offline_test_topics_20260827',
       update_time = NOW()
 WHERE id IN (21, 22, 23)
   AND del_flag = 0
   AND user_status = 1
   AND name IN ('副本人生', '好多好多不是吧', '测试主题-春日漫步');
