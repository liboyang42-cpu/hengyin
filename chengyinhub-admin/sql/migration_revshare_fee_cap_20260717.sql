-- ======================= 第二步:执行 =======================

ALTER TABLE `cms_topic_chapter`
  ADD COLUMN `max_per_head_fee` DECIMAL(10,2) NULL
  COMMENT '计酬档人头费上限(元/人次);NULL=未配置,fail-closed 拒绝计酬档入驻'
  AFTER `terms_mode`;

