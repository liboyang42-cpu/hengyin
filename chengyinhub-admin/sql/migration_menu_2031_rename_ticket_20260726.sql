SELECT menu_id, menu_name, perms, parent_id, menu_type, visible, status
FROM sys_menu WHERE menu_id = 2031;
-- 期望:2031 | 票务管理 | business:ticket:list | 2209 | C | 0 | 0
-- ★ 如果 menu_name 不是「票务管理」—— 有人已经改过 或 menu_id 漂了,
--   立即停止,不要执行后面的 UPDATE。

SELECT role_id FROM sys_role_menu WHERE menu_id = 2031 ORDER BY role_id;
-- 期望:2, 100, 101, 102, 103 (不改授权,但记录当前状态以便回读对比)

-- =====================================================================================
-- 二、改名 —— ★ 带 AND menu_name='票务管理' 守卫,幂等 + 防止在非预期行上生效
-- =====================================================================================
UPDATE sys_menu
SET menu_name = '票务定位'
WHERE menu_id = 2031
  AND menu_name = '票务管理';

