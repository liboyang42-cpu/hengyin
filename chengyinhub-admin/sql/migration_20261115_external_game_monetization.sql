-- 外部游戏（H5）上架后变现、分成配置、节点绑定、签名结果回执、反作弊流量激励与日结台账
-- 类别：② 新增表（只新增，不改 external_game_submission.ck_egs_money）。
-- 资金口径：真实收款与 TEST 现金结算仅在 chengyin.release.money-payments / payout 开启时放行，默认关闭；
-- 流量激励支持积分(POINTS)或 TEST 现金(TEST_MONEY)。

CREATE TABLE IF NOT EXISTS external_game_monetization_config (
  game_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'external_game.game_id',
  owner_member_id BIGINT NOT NULL COMMENT '创作者 member_id',
  pricing_mode VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'FREE' COMMENT 'FREE/PAID/TRAFFIC_ONLY',
  price_fen BIGINT NOT NULL DEFAULT 0 COMMENT '售价（分）；FREE/TRAFFIC_ONLY 时为 0',
  currency VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CNY',
  workshop_version_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '可选关联工坊版本标识',
  creator_share_bps INT NOT NULL DEFAULT 7000 COMMENT '创作者分成（万分比 0..10000）',
  channel_fee_bearer TINYINT NOT NULL DEFAULT 0 COMMENT '通道手续费承担方：0=创作者，1=平台',
  traffic_reward_mode VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'POINTS' COMMENT 'NONE/POINTS/TEST_MONEY',
  reward_per_play_points INT NOT NULL DEFAULT 5 COMMENT '每次有效游玩激励积分',
  reward_per_play_fen BIGINT NOT NULL DEFAULT 0 COMMENT '每次有效游玩激励 TEST 金额（分）',
  daily_user_cap INT NOT NULL DEFAULT 3 COMMENT '同玩家同游戏每日计入激励次数上限',
  daily_game_cap INT NOT NULL DEFAULT 200 COMMENT '单游戏每日计入激励总次数上限',
  min_duration_ms INT NOT NULL DEFAULT 5000 COMMENT '未通关时计入有效游玩的最小驻留毫秒',
  review_status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/PENDING/APPROVED/REJECTED',
  review_note VARCHAR(500) NULL COMMENT '审核说明或驳回原因',
  reviewer_id BIGINT NULL COMMENT 'sys_user.user_id',
  reviewed_time DATETIME(3) NULL,
  config_version BIGINT NOT NULL DEFAULT 1,
  request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  PRIMARY KEY (game_id),
  UNIQUE KEY uk_egmc_request (owner_member_id, request_id),
  KEY idx_egmc_review (review_status, update_time, game_id),
  CONSTRAINT ck_egmc_pricing CHECK (pricing_mode IN ('FREE', 'PAID', 'TRAFFIC_ONLY')),
  CONSTRAINT ck_egmc_price CHECK (price_fen >= 0 AND price_fen <= 2147483647 AND (pricing_mode <> 'PAID' OR price_fen > 0)),
  CONSTRAINT ck_egmc_bps CHECK (creator_share_bps BETWEEN 0 AND 10000),
  CONSTRAINT ck_egmc_bearer CHECK (channel_fee_bearer IN (0, 1)),
  CONSTRAINT ck_egmc_traffic_mode CHECK (traffic_reward_mode IN ('NONE', 'POINTS', 'TEST_MONEY')),
  CONSTRAINT ck_egmc_caps CHECK (daily_user_cap >= 0 AND daily_game_cap >= 0 AND min_duration_ms >= 0 AND reward_per_play_points >= 0 AND reward_per_play_fen >= 0),
  CONSTRAINT ck_egmc_review CHECK (review_status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='外部游戏变现、分成与流量激励配置';

CREATE TABLE IF NOT EXISTS external_game_order (
  id BIGINT NOT NULL AUTO_INCREMENT,
  order_no VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'EGO_<32hex>',
  game_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  seller_id BIGINT NOT NULL,
  buyer_id BIGINT NOT NULL,
  request_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  config_version BIGINT NOT NULL,
  amount_fen BIGINT NOT NULL,
  creator_share_bps INT NOT NULL,
  channel_fee_bearer TINYINT NOT NULL,
  channel_fee_fen BIGINT NOT NULL DEFAULT 0,
  creator_net_fen BIGINT NOT NULL DEFAULT 0,
  platform_share_fen BIGINT NOT NULL DEFAULT 0,
  currency VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CNY',
  provider VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'TEST_WALLET/WECHAT_APP/APPLE_IAP',
  workshop_order_no VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  state VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'PENDING/PAID/REVOKED/REFUNDED',
  license_status VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'PENDING/ACTIVE/REVOKED',
  paid_at DATETIME(3) NULL,
  creator_credited_at DATETIME(3) NULL,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_ego_order_no (order_no),
  UNIQUE KEY uk_ego_request (buyer_id, request_id),
  KEY idx_ego_game_buyer (game_id, buyer_id, state),
  KEY idx_ego_seller (seller_id, create_time),
  CONSTRAINT ck_ego_amount CHECK (amount_fen > 0 AND amount_fen <= 2147483647),
  CONSTRAINT ck_ego_provider CHECK (provider IN ('TEST_WALLET', 'WECHAT_APP', 'APPLE_IAP')),
  CONSTRAINT ck_ego_state CHECK (state IN ('PENDING', 'PAID', 'REVOKED', 'REFUNDED')),
  CONSTRAINT ck_ego_license CHECK (license_status IN ('PENDING', 'ACTIVE', 'REVOKED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='外部游戏购买订单与分账快照（TEST-only 真钱通道）';

CREATE TABLE IF NOT EXISTS external_game_entitlement (
  id BIGINT NOT NULL AUTO_INCREMENT,
  game_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  member_id BIGINT NOT NULL,
  order_no VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'ACTIVE',
  granted_at DATETIME(3) NOT NULL,
  revoked_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_ege_game_member (game_id, member_id),
  KEY idx_ege_member (member_id, status),
  CONSTRAINT ck_ege_status CHECK (status IN ('ACTIVE', 'REVOKED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='外部游戏已购授权权益';

CREATE TABLE IF NOT EXISTS external_game_node_binding (
  node_id BIGINT NOT NULL COMMENT 'cms_topic_node.id',
  topic_id BIGINT NOT NULL COMMENT 'cms_topic.id',
  game_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  owner_member_id BIGINT NOT NULL,
  min_score INT NOT NULL DEFAULT 0,
  require_pass TINYINT(1) NOT NULL DEFAULT 1,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  create_time DATETIME(3) NOT NULL,
  update_time DATETIME(3) NOT NULL,
  PRIMARY KEY (node_id),
  KEY idx_egnb_topic (topic_id, enabled),
  KEY idx_egnb_game (game_id, enabled)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='主题节点绑定外部游戏';

CREATE TABLE IF NOT EXISTS external_game_play_session (
  session_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  game_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  submission_id BIGINT NULL,
  creator_member_id BIGINT NOT NULL,
  member_id BIGINT NOT NULL,
  node_id BIGINT NULL,
  topic_id BIGINT NULL,
  activity_id BIGINT NULL,
  nonce CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  session_signature CHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端 Ed25519 对开局票据签名',
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'STARTED',
  passed TINYINT(1) NOT NULL DEFAULT 0,
  score INT NULL,
  duration_ms BIGINT NULL,
  result_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  result_signature CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'HMAC-SHA256(nonce, canonicalResult)',
  xp_awarded INT NOT NULL DEFAULT 0,
  medal_rank INT NULL,
  node_completed TINYINT(1) NOT NULL DEFAULT 0,
  traffic_eligible TINYINT(1) NOT NULL DEFAULT 0,
  fraud_reason VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  client_ip_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  play_date DATE NOT NULL,
  started_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  PRIMARY KEY (session_id),
  UNIQUE KEY uk_egps_nonce (nonce),
  KEY idx_egps_game_date (game_id, play_date, member_id, traffic_eligible),
  KEY idx_egps_member (member_id, started_at),
  CONSTRAINT ck_egps_status CHECK (status IN ('STARTED', 'COMPLETED', 'EXPIRED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='外部游戏开局票据与签名结果回执';

CREATE TABLE IF NOT EXISTS external_game_daily_settlement (
  id BIGINT NOT NULL AUTO_INCREMENT,
  settlement_date DATE NOT NULL,
  game_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  creator_member_id BIGINT NOT NULL,
  total_plays INT NOT NULL DEFAULT 0,
  valid_plays INT NOT NULL DEFAULT 0,
  capped_plays INT NOT NULL DEFAULT 0,
  reward_mode VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  settled_points INT NOT NULL DEFAULT 0,
  settled_fen BIGINT NOT NULL DEFAULT 0,
  status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'SETTLED/DEFERRED_MONEY_CLOSED/SKIPPED',
  note VARCHAR(255) NULL,
  settled_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_egds_date_game (settlement_date, game_id),
  KEY idx_egds_creator (creator_member_id, settlement_date),
  CONSTRAINT ck_egds_mode CHECK (reward_mode IN ('NONE', 'POINTS', 'TEST_MONEY')),
  CONSTRAINT ck_egds_status CHECK (status IN ('SETTLED', 'DEFERRED_MONEY_CLOSED', 'SKIPPED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='外部游戏流量激励日结台账';
