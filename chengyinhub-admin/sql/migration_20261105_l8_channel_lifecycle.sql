-- Additive source only; no historical conversation backfill or production execution.
-- Existing conversation IDs/types and message rows are never rewritten here.
CREATE TABLE im_channel (
    id BIGINT UNSIGNED NOT NULL,
    guild_kind TINYINT NOT NULL DEFAULT 0,
    guild_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
    parent_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
    kind TINYINT NOT NULL DEFAULT 1,
    name VARCHAR(64) NOT NULL,
    topic VARCHAR(120) NULL,
    position INT NOT NULL DEFAULT 0,
    is_default TINYINT NOT NULL DEFAULT 0,
    opt_in_default TINYINT NOT NULL DEFAULT 0,
    status TINYINT NOT NULL DEFAULT 0,
    archive_reason VARCHAR(64) NULL,
    archived_at DATETIME(3) NULL,
    delete_reason VARCHAR(120) NULL,
    purge_at DATETIME(3) NULL,
    visibility TINYINT NOT NULL DEFAULT 1,
    flags INT NOT NULL DEFAULT 0,
    age_gate TINYINT NOT NULL DEFAULT 0,
    age_gate_text VARCHAR(120) NULL,
    slowmode_sec SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    bot_enabled TINYINT NOT NULL DEFAULT 1,
    feed_source TINYINT NOT NULL DEFAULT 0,
    feed_ref BIGINT UNSIGNED NOT NULL DEFAULT 0,
    perm_version INT NOT NULL DEFAULT 0,
    legacy_conversation_id BIGINT UNSIGNED NULL,
    idempotency_key VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NULL,
    del_flag TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    update_by VARCHAR(64) NULL,
    update_time DATETIME(3) NULL,
    remark VARCHAR(255) NULL,
    default_guard BIGINT UNSIGNED GENERATED ALWAYS AS (IF(is_default=1 AND guild_id>0,guild_id,NULL)) STORED,
    name_guard VARCHAR(64) GENERATED ALWAYS AS (IF(del_flag=0,name,NULL)) STORED,
    is_spoiler TINYINT GENERATED ALWAYS AS (IF((flags & 2097152)<>0,1,0)) STORED,
    PRIMARY KEY(id),
    UNIQUE KEY uk_channel_default(guild_kind,default_guard),
    UNIQUE KEY uk_channel_name(guild_kind,guild_id,parent_id,name_guard),
    UNIQUE KEY uk_channel_create_request(idempotency_key),
    KEY idx_channel_tree(guild_kind,guild_id,del_flag,status,position),
    KEY idx_channel_parent(parent_id,position),
    KEY idx_channel_purge(status,purge_at),
    CONSTRAINT ck_channel_kind CHECK(kind IN (0,1,2,3,6,7,8)),
    CONSTRAINT ck_channel_status CHECK(status IN (0,1,2,3,4)),
    CONSTRAINT ck_channel_visibility CHECK(visibility IN (1,2)),
    CONSTRAINT ck_channel_scope CHECK((kind IN (0,1,2,3) AND guild_kind BETWEEN 1 AND 7 AND guild_id>0)
        OR (kind IN (6,7,8) AND guild_kind=0 AND guild_id=0 AND parent_id=0)),
    CONSTRAINT ck_channel_default CHECK(is_default IN (0,1) AND (is_default=0 OR (kind=1 AND position=0 AND guild_id>0))),
    CONSTRAINT ck_channel_opt_in CHECK(opt_in_default IN (0,1) AND (opt_in_default=0 OR (kind IN (1,2,3) AND status=0))),
    CONSTRAINT ck_channel_purge CHECK(status NOT IN (3,4) OR purge_at IS NOT NULL),
    CONSTRAINT ck_channel_parent CHECK(parent_id<>id),
    CONSTRAINT ck_channel_slowmode CHECK(slowmode_sec<=21600),
    CONSTRAINT ck_channel_age CHECK(age_gate IN (0,1,2)),
    CONSTRAINT ck_channel_feed CHECK((feed_source IN (0,1) AND feed_ref=0) OR (feed_source=2 AND feed_ref>0)),
    CONSTRAINT ck_channel_version CHECK(perm_version>=0),
    CONSTRAINT ck_channel_deleted CHECK(del_flag IN (0,1)),
    CONSTRAINT ck_channel_legacy CHECK(legacy_conversation_id IS NULL OR legacy_conversation_id=id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE im_channel_op_log (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    channel_id BIGINT UNSIGNED NOT NULL,
    action VARCHAR(32) NOT NULL,
    from_status TINYINT NULL,
    to_status TINYINT NULL,
    reason VARCHAR(120) NOT NULL,
    operator_id BIGINT NULL,
    request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY(id),
    KEY idx_channel_op(channel_id,create_time),
    KEY idx_channel_op_request(operator_id,request_id),
    CONSTRAINT ck_channel_op_reason CHECK(CHAR_LENGTH(TRIM(reason))>0),
    CONSTRAINT ck_channel_op_action CHECK(action IN ('CREATE','ARCHIVE','UNARCHIVE','BAN','UNBAN','DELETE','RESTORE','MOVE','TRANSFER_BUMP'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Immutable original response; no TTL and no inferred historical receipts.
CREATE TABLE im_channel_lifecycle_receipt (
    operator_id BIGINT NOT NULL,
    request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    response_json LONGTEXT NULL,
    create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY(operator_id,request_id),
    CONSTRAINT ck_channel_lifecycle_json CHECK(response_json IS NULL OR JSON_VALID(response_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
