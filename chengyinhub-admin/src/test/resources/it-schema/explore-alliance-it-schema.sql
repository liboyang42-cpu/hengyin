-- 探店日联盟局两套真库 IT 的建表脚本（结构，不含数据）。
--
-- 为什么要有这个文件：这两套 IT 原本硬编码连本机 3306 上一个长期存在的 chengyin_explore_it
-- （由 `mysqldump --no-data 生产` 手工灌出来的库）。后果有三条，2026-08-17 全部实测坐实：
--   ① 它不读 CHENGYIN_TEST_MYSQL_* ⇒ 资金门禁把连接指到别处也没用，实跑的是另一台库
--      （本机那台是 MySQL 9.7.1，不是验收档要求的 Oracle 8.0.45）；
--   ② 库是跨运行长期存在的，违反门禁自己写的「唯一临时 schema，跑完 DROP」；
--   ③ 它的 schema 会过期 —— oms_ticket 缺了 R6 产品迁移加的 source_ticket_id，
--      于是 5 条用例长期报 ERROR 1054，而没人看得见，因为这套件从来没在门禁里真跑过。
--
-- 现在：测试自己决定 schema（与 ItSchema 的既有原则一致），建表用本文件，
-- 再由 IT 在其上叠加仓库里的 migration（例如 R6 产品合同补 source_ticket_id），
-- 所以「结构跟着仓库演进走」，不再依赖环境里恰好剩下什么。

