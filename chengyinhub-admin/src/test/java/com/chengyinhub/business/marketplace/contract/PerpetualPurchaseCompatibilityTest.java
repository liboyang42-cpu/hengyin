package com.chengyinhub.business.marketplace.contract;

import com.chengyinhub.business.marketplace.free.FreePublicationSnapshot;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.junit.jupiter.api.Test;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Scanner;
import static org.junit.jupiter.api.Assertions.*;

class PerpetualPurchaseCompatibilityTest {
    private static final byte[] CONTENT = ("{\"schema\":\"w18-member-text-v1\",\"title\":\"fixture\","
            + "\"questionAnswer\":\"private-fixture-answer\",\"bindings\":{}}").getBytes(StandardCharsets.UTF_8);
    private static final byte[] TERMS = {1};

    private String golden() throws Exception {
        try (InputStream input = getClass().getResourceAsStream(
                "/contracts/marketplace/legacy-free-publication-duration-v1.json")) {
            assertNotNull(input);
            return new Scanner(input, "UTF-8").useDelimiter("\\A").next().trim();
        }
    }

    @Test void historicalFrozenFreeDocumentAndHashRemainByteForByteReadable() throws Exception {
        // Golden produced by the unchanged 82a6fd8 codec, never regenerated by this test.
        String encoded = golden();
        FreePublicationSnapshot read = FreePublicationSnapshot.decode(encoded, CONTENT, TERMS);
        assertEquals(encoded, read.encode());
        assertNull(read.getOffer().getTerms().getUseDuration());
        assertEquals(LicenseOfferSnapshot.Acquisition.FREE, read.getOffer().getAcquisition());
        assertEquals(java.time.Instant.parse("2030-01-01T00:00:00Z"), read.getValidUntil());
    }

    @Test void injectingPurchaseDurationIntoFrozenFreeDocumentFailsClosed() throws Exception {
        ObjectNode root = (ObjectNode) new ObjectMapper().readTree(golden());
        ((ObjectNode) root.path("offer").path("terms")).put("useDuration", "PERPETUAL_PURCHASED_VERSION");
        assertThrows(IllegalArgumentException.class, () -> FreePublicationSnapshot.decode(root.toString(), CONTENT, TERMS));
        ((ObjectNode) root.path("offer").path("terms")).putNull("useDuration");
        assertThrows(IllegalArgumentException.class, () -> FreePublicationSnapshot.decode(root.toString(), CONTENT, TERMS));
    }
}
