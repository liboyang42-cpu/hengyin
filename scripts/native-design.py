#!/usr/bin/env python3
"""Export existing Mini tokens to Swift; check task-scoped native page pairs."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    return json.loads(path.read_text())


def git_environment(repo):
    environment = os.environ.copy()
    if repo.resolve() != Path.cwd().resolve():
        for name in subprocess.check_output(["git", "rev-parse", "--local-env-vars"], text=True).splitlines():
            environment.pop(name, None)
    return environment


def staged_text(repo, path):
    result = subprocess.run(["git", "-C", str(repo), "show", ":" + path], capture_output=True, env=git_environment(repo))
    if result.returncode:
        raise ValueError(f"Missing staged/tracked design source: {repo.name}/{path}")
    return result.stdout.decode("utf-8")


def verify_baseline(repo, baseline):
    commit = baseline["commit"]
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError("Invalid approved App baseline commit")
    result = subprocess.run(["git", "-C", str(repo), "merge-base", "--is-ancestor", commit, "HEAD"], capture_output=True, env=git_environment(repo))
    if result.returncode:
        raise ValueError(f"App checkout is not based on approved {baseline.get('ref', 'source')} {commit[:12]}; verify the latest native source before generating or checking")


def root_tokens(source):
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    block = re.search(r"(?:^|\n)page\s*\{([^{}]*)\}", source)
    if not block:
        raise ValueError("Missing plain page token scope")
    pairs = re.findall(r"(--cy-[\w-]+)\s*:\s*([^;]+);", block[1])
    result = {}
    for name, value in pairs:
        if name in result:
            raise ValueError("Duplicate root token: " + name)
        result[name] = value.strip()
    return result


def points(name, tokens, width):
    value = tokens[name]
    match = re.fullmatch(r"(\d+(?:\.\d+)?)rpx", value)
    if not match:
        raise ValueError(f"{name}: expected a literal rpx dimension, got {value}")
    return format(float(match[1]) * width / 750, ".12g")


def render(config, tokens):
    def accent(mode):
        color = config["iosAccent"][mode]
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", color):
            raise ValueError("Invalid native accent: " + mode)
        r, g, b = (int(color[i:i + 2], 16) for i in (1, 3, 5))
        return f"UIColor(red:{r}.0/255,green:{g}.0/255,blue:{b}.0/255,alpha:1)"

    width = config["referenceWidth"]
    if not isinstance(width, (int, float)) or not 0 < width <= 750:
        raise ValueError("Invalid referenceWidth")
    sections = []
    for group, swift in (("spacing", "Space"), ("radius", "Radius")):
        lines = [f"    enum {swift} {{"]
        for name, token in config[group].items():
            lines.append(f"        static let {name}: CGFloat = {points(token, tokens, width)}")
        sections.append("\n".join(lines + ["    }"]))
    for group, swift, kind in (("colors", "Colors", "Color"), ("typography", "Typography", "Font")):
        lines = [f"    enum {swift} {{"]
        for name, mapping in config[group].items():
            if mapping["mini"] not in tokens:
                raise ValueError("Unknown semantic token: " + mapping["mini"])
            lines.append(f'        static let {name}: {kind} = {mapping["ios"]}')
        sections.append("\n".join(lines + ["    }"]))
    return ("// Generated by scripts/native-design.py from tokens.wxss and design/native/design-map.json.\n"
            "// Edit the sources, then regenerate; keep Dynamic Type and system semantic colors.\n"
            "import SwiftUI\nimport UIKit\n\n"
            "/// Brand tint with separate light/dark values; keeps native control semantics and shapes.\n"
            "enum QuestifyPalette {\n"
            "    static let accent=Color(UIColor { traits in\n"
            "        if traits.userInterfaceStyle == .dark {\n"
            f'            return {accent("dark")}\n'
            "        }\n"
            f'        return {accent("light")}\n'
            "    })\n}\n\n"
            "/// Shared design roles; dimensions use the reference canvas, not the device width.\n"
            "enum QuestifyDesign {\n" + "\n".join(sections) + "\n}\n")


def pair_errors(pairs, mini_paths, ios_paths, reviewed_mini_paths=(), reviewed_ios_paths=()):
    errors = []
    actual = {"mini": set(mini_paths), "ios": set(ios_paths)}
    paths = {"mini": list(mini_paths) + list(reviewed_mini_paths),
             "ios": list(ios_paths) + list(reviewed_ios_paths)}
    matched = {"mini": set(), "ios": set()}
    for name, mapping in pairs.items():
        covered = {}
        for side in paths:
            covered[side] = {p for p in paths[side] if any(
                p.startswith(pattern) if pattern.endswith("/") else p == pattern
                for pattern in mapping[side])}
            matched[side].update(covered[side])
        if any(actual[side] & covered[side] for side in paths) and bool(covered["mini"]) != bool(covered["ios"]):
            errors.append(name + ": only one native client changed; implement the counterpart or record the platform exception in the task")
    for side in paths:
        for path in sorted(set(paths[side]) - matched[side]):
            errors.append(f"{side}: unmapped path {path}; add its real counterpart before claiming pair coverage")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["check", "write"])
    parser.add_argument("--ios-root", type=Path, required=True)
    parser.add_argument("--mini-path", action="append", default=[], help="Task-owned path relative to chengyinhub-xcx; repeat as needed")
    parser.add_argument("--ios-path", action="append", default=[], help="Task-owned path relative to the native repo; repeat as needed")
    parser.add_argument("--reviewed-mini-path", action="append", default=[], help="Unchanged Mini counterpart verified in this task")
    parser.add_argument("--reviewed-ios-path", action="append", default=[], help="Unchanged native counterpart verified in this task")
    parser.add_argument("--review-note", help="Why reviewed counterparts need no code change")
    parser.add_argument("--staged-side", choices=["mini", "ios"], help="Pre-commit: check index contents, not unstaged edits")
    args = parser.parse_args()
    if args.staged_side:
        if args.action != "check" or args.mini_path or args.ios_path or args.reviewed_mini_path or args.reviewed_ios_path:
            raise ValueError("--staged-side is only for token checks")
        repo = ROOT if args.staged_side == "mini" else args.ios_root
        changed = subprocess.run(["git", "-C", str(repo), "diff", "--cached", "--name-only", "-z"], capture_output=True, check=True, env=git_environment(repo)).stdout.decode().split("\0")
        mapped = load(ROOT / "design/native/page-pairs.json")
        prefix = "chengyinhub-xcx/" if args.staged_side == "mini" else ""
        watched = [prefix + path for group in mapped.values() for path in group[args.staged_side]]
        if args.staged_side == "mini":
            watched += ["design/native/baseline.json", "design/native/design-map.json", "design/native/page-pairs.json", "scripts/native-design.py"]
        if not any(path.startswith(pattern) if pattern.endswith("/") else path == pattern for path in changed for pattern in watched):
            return
    mini = ROOT / "chengyinhub-xcx"
    target = args.ios_root.resolve() / "App/QuestifyPalette.swift"
    if not target.is_file() or not (args.ios_root / "Questify.xcodeproj").is_dir():
        raise ValueError("Not the existing Questify native checkout")
    baseline = (json.loads(staged_text(ROOT, "design/native/baseline.json")) if args.staged_side
                else load(ROOT / "design/native/baseline.json"))
    verify_baseline(args.ios_root, baseline)
    config = (json.loads(staged_text(ROOT, "design/native/design-map.json")) if args.staged_side
              else load(ROOT / "design/native/design-map.json"))
    pairs = load(ROOT / "design/native/page-pairs.json")
    for mapping in pairs.values():
        for side, base in (("mini", mini), ("ios", args.ios_root)):
            for path in mapping[side]:
                if not (base / path).exists():
                    raise ValueError(f"Missing mapped source: {side}/{path}")
    source = (staged_text(ROOT, "chengyinhub-xcx/style/tokens.wxss") if args.staged_side
              else (mini / "style/tokens.wxss").read_text())
    expected = render(config, root_tokens(source))
    actual = (staged_text(args.ios_root, "App/QuestifyPalette.swift") if args.staged_side == "ios"
              else target.read_text())
    reviewed = args.reviewed_mini_path + args.reviewed_ios_path
    if reviewed and not (args.review_note or "").strip():
        raise ValueError("Reviewed unchanged counterparts require --review-note")
    for paths, base in ((args.mini_path + args.reviewed_mini_path, mini), (args.ios_path + args.reviewed_ios_path, args.ios_root)):
        for path in paths:
            resolved = (base / path).resolve()
            if not resolved.is_relative_to(base.resolve()) or not resolved.is_file():
                raise ValueError("Not an existing counterpart source file: " + path)
    errors = pair_errors(pairs, args.mini_path, args.ios_path,
                         reviewed_mini_paths=args.reviewed_mini_path, reviewed_ios_paths=args.reviewed_ios_path)
    if errors:
        raise ValueError("\n".join(errors))
    if args.action == "write":
        if target.read_text() != expected:
            target.write_text(expected)
        print("Wrote native design tokens; Mini token values were not rewritten.")
    elif actual != expected:
        raise ValueError("Native design tokens drifted; run write with the same --ios-root")
    print(f"PASS: {len(config['spacing']) + len(config['radius'])} shared dimensions; native semantic color/type mappings; {len(pairs)} source groups.")
    if reviewed:
        print("Reviewed unchanged counterparts (not edits): " + ", ".join(reviewed))
        print("Review note: " + args.review_note)
    if not args.mini_path and not args.ios_path:
        print("Page change coverage NOT CHECKED: provide this task's --mini-path and --ios-path lists.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError) as error:
        sys.exit(str(error))
